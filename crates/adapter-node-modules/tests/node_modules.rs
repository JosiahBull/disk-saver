//! Integration tests for the `node-modules` adapter, driven end-to-end against
//! [`FakePlatform`] through the public [`factory`] surface (no real filesystem).

use std::time::{Duration, SystemTime, UNIX_EPOCH};

use disk_saver_adapter_node_modules::factory;
use disk_saver_core::{
    Adapter, Candidate, Class, Ctx, DecisionLog, Outcome, Platform, Pressure, Store,
};
use disk_saver_platform::FakePlatform;

const DAY: u64 = 24 * 60 * 60;

/// A fixed `SystemTime` `days` days after the unix epoch. The fake clock's
/// default `now` is `UNIX_EPOCH + 400 days`, so `at(400 - n)` is "n days ago".
fn at(days: u64) -> SystemTime {
    UNIX_EPOCH + Duration::from_secs(days * DAY)
}

/// Build the adapter from default config.
fn adapter_default() -> Box<dyn Adapter> {
    (factory().build)(None).unwrap()
}

/// Build the adapter from a small TOML snippet.
fn adapter_from(toml: &str) -> Box<dyn Adapter> {
    let raw: toml::Value = toml::from_str(toml).unwrap();
    (factory().build)(Some(raw)).unwrap()
}

/// A fake with one node project under `~/dev/app`: a `package.json` whose mtime
/// (day `pkg_day`) drives `last_active`, and a `1_000`-byte `node_modules`.
fn fake_with_project(pkg_day: u64) -> FakePlatform {
    FakePlatform::new()
        .with_file("~/dev/app/package.json", "{}", at(pkg_day))
        .with_file("~/dev/app/index.js", "code", at(pkg_day))
        // node_modules' own mtime is deliberately ignored by the scan; give it a
        // very recent stamp to prove it does not affect the age decision.
        .with_sized_dir("~/dev/app/node_modules", 1_000, at(399))
}

/// Run observe + plan against `fake` at the given pressure.
fn plan_at(
    fake: &FakePlatform,
    adapter: &mut Box<dyn Adapter>,
    pressure: Pressure,
) -> Vec<Candidate> {
    let store = Store::open_in_memory().unwrap();
    let log = DecisionLog::disabled();
    let mut ctx = Ctx::new(fake, store.bucket("node-modules"), pressure, &log);
    adapter.observe(&mut ctx).unwrap();
    adapter.plan(&mut ctx).unwrap()
}

const NM_PATH: &str = "/home/tester/dev/app/node_modules";

// ── age × pressure eligibility ─────────────────────────────────────────────

#[test]
fn comfortable_deletes_nothing_even_when_ancient() {
    // 200 days idle — far past any threshold — but Comfortable is always a no-op.
    let fake = fake_with_project(200);
    let mut adapter = adapter_default();
    let candidates = plan_at(&fake, &mut adapter, Pressure::Comfortable);
    assert!(candidates.is_empty());
}

#[test]
fn normal_requires_max_age() {
    // Idle 40 days > max_age (30d) → eligible under Normal.
    let fake = fake_with_project(360);
    let mut adapter = adapter_default();
    let candidates = plan_at(&fake, &mut adapter, Pressure::Normal);
    assert_eq!(candidates.len(), 1);
    let c = &candidates[0];
    assert_eq!(c.id, NM_PATH);
    assert_eq!(c.bytes, 1_000);
    assert_eq!(c.class, Class::Cache);
    assert_eq!(c.last_used, at(360));
    assert!(!c.requires_confirmation);
    assert_eq!(c.label, "node_modules in /home/tester/dev/app");
}

#[test]
fn normal_keeps_recent_project() {
    // Idle only 10 days < max_age (30d) → not eligible under Normal.
    let fake = fake_with_project(390);
    let mut adapter = adapter_default();
    let candidates = plan_at(&fake, &mut adapter, Pressure::Normal);
    assert!(candidates.is_empty());
}

#[test]
fn scavenge_reaches_below_max_age_but_respects_min_age_floor() {
    // Idle 10 days: below max_age (30d) so Normal keeps it, but above min_age
    // (7d) so Scavenge reaches it.
    let fake = fake_with_project(390);
    let mut adapter = adapter_default();
    assert!(plan_at(&fake, &mut adapter, Pressure::Normal).is_empty());

    let mut adapter = adapter_default();
    let candidates = plan_at(&fake, &mut adapter, Pressure::Scavenge { need: 1 << 30 });
    assert_eq!(
        candidates.len(),
        1,
        "scavenge should reach a 10-day-idle project"
    );
}

#[test]
fn min_age_floor_protects_very_recent_project_under_scavenge() {
    // Idle only 3 days < min_age (7d): untouchable even at max pressure (§11.2).
    let fake = fake_with_project(397);
    let mut adapter = adapter_default();
    let candidates = plan_at(&fake, &mut adapter, Pressure::Scavenge { need: 1 << 40 });
    assert!(candidates.is_empty());
}

// ── strict identification & guardrails ─────────────────────────────────────

#[test]
fn missing_package_json_is_not_found() {
    // node_modules present but no package.json sibling → never a candidate.
    let fake = FakePlatform::new().with_sized_dir("~/dev/app/node_modules", 1_000, at(200));
    let mut adapter = adapter_default();
    let candidates = plan_at(&fake, &mut adapter, Pressure::Scavenge { need: 1 << 40 });
    assert!(candidates.is_empty());
}

#[test]
fn disk_saver_keep_sentinel_is_respected() {
    let fake = fake_with_project(200).with_file("~/dev/app/.disk-saver-keep", "", at(200));
    let mut adapter = adapter_default();
    let candidates = plan_at(&fake, &mut adapter, Pressure::Normal);
    assert!(candidates.is_empty());
}

#[test]
fn denylist_root_under_library_is_dropped() {
    // A project living under ~/Library must never be swept even if configured.
    let fake = FakePlatform::new()
        .with_file("~/Library/app/package.json", "{}", at(100))
        .with_sized_dir("~/Library/app/node_modules", 1_000, at(100));
    let mut adapter = adapter_from(r#"roots = ["~/Library"]"#);
    let candidates = plan_at(&fake, &mut adapter, Pressure::Scavenge { need: 1 << 40 });
    assert!(candidates.is_empty());
}

#[test]
fn confirm_true_flags_the_candidate() {
    let fake = fake_with_project(200);
    let mut adapter = adapter_from("confirm = true");
    let candidates = plan_at(&fake, &mut adapter, Pressure::Normal);
    assert_eq!(candidates.len(), 1);
    assert!(candidates[0].requires_confirmation);
}

// ── execute ────────────────────────────────────────────────────────────────

#[test]
fn execute_removes_and_records_the_removal() {
    let fake = fake_with_project(200);
    let mut adapter = adapter_default();

    let store = Store::open_in_memory().unwrap();
    let log = DecisionLog::disabled();
    let mut ctx = Ctx::new(&fake, store.bucket("node-modules"), Pressure::Normal, &log);

    adapter.observe(&mut ctx).unwrap();
    let candidates = adapter.plan(&mut ctx).unwrap();
    assert_eq!(candidates.len(), 1);

    let outcomes = adapter.execute(&mut ctx, &candidates).unwrap();
    assert_eq!(outcomes.len(), 1);
    match &outcomes[0] {
        Outcome::Removed { id, bytes } => {
            assert_eq!(id, NM_PATH);
            assert_eq!(*bytes, 1_000);
        }
        other => panic!("expected Removed, got {other:?}"),
    }

    // The removal was carried out and recorded by the platform, and the
    // directory is gone.
    assert!(
        fake.removed()
            .iter()
            .any(|p| p == std::path::Path::new(NM_PATH))
    );
    assert!(!fake.exists(NM_PATH));
}

#[test]
fn execute_skips_when_package_json_vanished_after_plan() {
    let fake = fake_with_project(200);
    let mut adapter = adapter_default();

    let store = Store::open_in_memory().unwrap();
    let log = DecisionLog::disabled();
    let mut ctx = Ctx::new(&fake, store.bucket("node-modules"), Pressure::Normal, &log);

    adapter.observe(&mut ctx).unwrap();
    let candidates = adapter.plan(&mut ctx).unwrap();
    assert_eq!(candidates.len(), 1);

    // The marker disappears between plan and execute.
    Platform::remove_file(
        &fake,
        std::path::Path::new("/home/tester/dev/app/package.json"),
    )
    .unwrap();

    let outcomes = adapter.execute(&mut ctx, &candidates).unwrap();
    assert_eq!(outcomes.len(), 1);
    assert!(
        matches!(&outcomes[0], Outcome::Skipped { .. }),
        "expected Skipped, got {:?}",
        outcomes[0]
    );
    // Because we skipped, node_modules is untouched.
    assert!(fake.exists(NM_PATH));
    assert!(
        !fake
            .removed()
            .iter()
            .any(|p| p == std::path::Path::new(NM_PATH))
    );
}

#[test]
fn execute_skips_when_node_modules_already_gone() {
    // A candidate that points at a directory that no longer exists is skipped,
    // not failed.
    let fake = fake_with_project(200);
    let mut adapter = adapter_default();

    let candidate = Candidate::new(
        "/home/tester/dev/gone/node_modules",
        "node_modules in /home/tester/dev/gone",
        500,
        at(200),
        Class::Cache,
    );

    let store = Store::open_in_memory().unwrap();
    let log = DecisionLog::disabled();
    let mut ctx = Ctx::new(&fake, store.bucket("node-modules"), Pressure::Normal, &log);

    let outcomes = adapter.execute(&mut ctx, &[candidate]).unwrap();
    assert!(matches!(&outcomes[0], Outcome::Skipped { .. }));
}
